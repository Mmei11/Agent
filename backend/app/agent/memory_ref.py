"""Phase A：识别“记忆指代”类追问。

“我刚才说想什么时候去？”“之前提到的那个安排是什么？”
这类问题的答案不在结构化字段里，而在对话记录里。单路由只看到当前消息，
会把它们当成普通闲聊直接回答，于是出现“你之前没有提到过”的错觉。

这里用确定性模式先识别，命中后跳过单路由，交给带上下文的 answer 节点。
只负责“要不要走记忆路径”，不生成答案。
"""

import re

# 每条模式都要求出现“回忆动作 + 指代对象”，避免把普通陈述误判成记忆问题。
MEMORY_REFERENCE_PATTERNS = (
    # 我刚才说 / 之前提到 / 前面讲过 / 最开始问过 / 最早说
    re.compile(r"我(刚才|刚刚|之前|前面|上次|一开始|最开始|最早|先前)(说|讲|提|问|聊)"),
    # 你还记得 / 您记得
    re.compile(r"(你|您)(还)?记得"),
    # 我说过什么 / 我说过啥
    re.compile(r"我说过(什么|啥|哪些)"),
    # 之前提到的 / 刚才说过的（不强制带“我”）
    re.compile(r"(刚才|刚刚|之前|前面|上次)(说|讲|提|问|聊)"),
    # 刚才那句 / 之前的那个 / 前面的那些
    re.compile(r"(刚才|刚刚|之前|前面)的?(那句|那个|那段|那些|话|问题|信息|内容|症状|安排|偏好)"),
    # 我说的是什么 / 我提的是哪里
    re.compile(r"我(说|提)的(是)?(什么|啥|哪个|哪里|哪些)"),
)


def is_memory_reference(message: str) -> bool:
    """判断这条消息是否要求回忆前面说过的话。"""
    text = (message or "").strip()
    if not text:
        return False
    return any(pattern.search(text) for pattern in MEMORY_REFERENCE_PATTERNS)
